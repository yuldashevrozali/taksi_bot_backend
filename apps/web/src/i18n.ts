/** Clients only see PENDING / ACCEPTED / CANCELLED; "Yo'lda" and "Yakunlandi" are driver-only stages. */
export function clientStatus(status: OrderStatus): "PENDING" | "ACCEPTED" | "CANCELLED" {
  return status === "PENDING" || status === "CANCELLED" ? status : "ACCEPTED";
}

export const DICTS: Record<Language, Dict> = { UZ_LATN: latn, UZ_CYRL: cyrl };

/** City names are stored in Latin; show them in Cyrillic for UZ_CYRL users. */
const CITY_CYRL: Record<string, string> = { "Farg'ona": "Фарғона", "Qo'qon": "Қўқон" };
export function city(name: string, lang: Language): string {
  return lang === "UZ_CYRL" ? (CITY_CYRL[name] ?? name) : name;
}
